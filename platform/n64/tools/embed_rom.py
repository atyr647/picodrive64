#!/usr/bin/env python3
"""embed_rom.py ROM NAME [OUT]: generate platform/n64/embedded_rom.h for a
Mega Drive ROM (raw big-endian .md/.bin/.gen, as the Gley Lancer one is)."""
import sys
rom = open(sys.argv[1], 'rb').read()
name = sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else 'platform/n64/embedded_rom.h'
if len(rom) >= 0x200 and rom[0x100:0x104] not in (b'SEGA', b' SEG'):
    sys.stderr.write('warning: no SEGA header at 0x100 (interleaved .smd?)\n')
with open(out, 'w') as f:
    f.write('/* Auto-generated by platform/n64/tools/embed_rom.py: %s */\n' % name)
    f.write('#ifndef EMBEDDED_ROM_H\n#define EMBEDDED_ROM_H\n\n')
    f.write('#define EMBEDDED_ROM_SIZE %d\n' % len(rom))
    f.write('#define EMBEDDED_ROM_NAME "%s"\n\n' % name.replace('"', ''))
    f.write('static const unsigned char embedded_rom_data[] __attribute__((aligned(16))) = {\n')
    for i in range(0, len(rom), 16):
        f.write('  ' + ','.join('0x%02x' % b for b in rom[i:i + 16]) + ',\n')
    f.write('};\n\n#endif\n')
print('%s: %d bytes -> %s' % (name, len(rom), out))
