#!/usr/bin/env python3
"""make_ordering.py LOG ELF OUT [MIN_SAMPLES]

Turn an N64_PROF_SAMPLE run (see main_n64.c / prof_report.py) into a GNU ld
--section-ordering-file that places the hottest functions first in .text,
hottest first.  The VR4300's 16 KB I-cache is direct-mapped: packing the hot
set together keeps it from colliding with itself (FAME alone is ~1900
separate opcode handlers spread over ~330 KB), and pins its layout so that
unrelated code changes stop shifting it around.

Section names are .text.<function> (-ffunction-sections); LTO/IPA clones
get suffixes (.lto_priv.N, .constprop.N, .isra.N, .part.N), so each entry
matches the base name with any suffix.
"""
import bisect, subprocess, sys

args = [a for a in sys.argv[1:] if not a.startswith("--")]
group_mode = "--group" in sys.argv
log, elf, out = args[0], args[1], args[2]
min_samples = int(args[3]) if len(args) > 3 else 2

# --group: order by subsystem first (68k, z80, vdp, sound, other), hottest
# first within each, so each component's hot code is contiguous instead of
# interleaved with the others' (they run in separate phases of a frame).
GROUPS = [
    ("68k", ("OP_0x", "fm68k", "m68k_", "PicoRead", "PicoWrite", "PicoVideo",
             "CommandDma", "DmaSlow", "SekInterrupt", "io_ports", "port_read",
             "ctl_write", "vdp_")),
    ("z80", ("Cz80", "z80_", "ym2612_read_local_z80", "ym2612_write_local",
             "PsndDoDAC", "PsndDoPSG", "SN76496", "ym2612_sync")),
    ("vdp", ("Draw", "PicoFrameFull", "BackFill", "Tile", "PicoDraw")),
    ("snd", ("YM2612", "update_eg", "Psnd", "rsp_fm", "mix_", "write_sound",
             "refresh_fc", "OPN", "chan_")),
]
def group_of(base):
    for i, (_, prefixes) in enumerate(GROUPS):
        if base.startswith(prefixes):
            return i
    return len(GROUPS)
nm = "/opt/libdragon/bin/mips64-elf-nm"

syms = []
for line in subprocess.run([nm, "-n", "-S", "--defined-only", elf],
                           capture_output=True, text=True).stdout.splitlines():
    p = line.split()
    if len(p) >= 4 and p[2] in "tTwW":
        syms.append((int(p[0], 16), int(p[1], 16), p[3]))
syms.sort()
addrs = [s[0] for s in syms]

per = {}
for line in open(log, errors="replace"):
    if line.startswith("[PS] "):
        _, a, c = line.split()
        a = int(a, 16)
        i = bisect.bisect_right(addrs, a) - 1
        if i >= 0 and a < syms[i][0] + max(syms[i][1], 1):
            per[syms[i][2]] = per.get(syms[i][2], 0) + int(c)

bases, seen, total, kept = [], set(), sum(per.values()), 0
order = sorted(per.items(), key=lambda x: -x[1])
if group_mode:
    order.sort(key=lambda x: group_of(x[0].split(".")[0]))  # stable: hotness kept within group
for name, c in order:
    if c < min_samples:
        continue
    base = name.split(".")[0]
    if base and base not in seen:
        seen.add(base)
        bases.append(base)
        kept += c

with open(out, "w") as f:
    f.write("/* Generated by platform/n64/tools/make_ordering.py from a PC-sample\n")
    f.write(" * profile; %d hot functions covering %.1f%% of samples. */\n"
            % (len(bases), 100.0 * kept / max(total, 1)))
    f.write(".text : {\n")
    for b in bases:
        f.write("  *(.text.%s .text.%s.*)\n" % (b, b))
    f.write("}\n")
print("wrote %s: %d functions, %.1f%% of samples" % (out, len(bases), 100.0 * kept / max(total, 1)))
